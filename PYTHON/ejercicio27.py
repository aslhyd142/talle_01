numero_de_mes=int(input("ingrese el numero del mes:"))
if(numero_de_mes==12 or numero_de_mes==1 or numero_de_mes==2):
    print("la estacion es verano")
elif(numero_de_mes==3 or numero_de_mes==4 or numero_de_mes==5):
    print("la estacion es otoño")

elif(numero_de_mes==6 or numero_de_mes==7 or numero_de_mes==8):
    print("la estacion es invierno")

elif(numero_de_mes==9 or numero_de_mes==10 or numero_de_mes==11):
    print("la estacion es primavera")
